"""Build manuscript displays from retained summaries, without simulation or fitting.

Run from any directory with Python, NumPy, and Matplotlib. All inputs are tracked
report tables. The manifest records exactly which bytes supplied each display.
"""

from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.lines import Line2D


ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"
BD = ROOT / "reports/founder-mixture-birth-death/tables"
METHODS = ["G", "EG", "M0", "Mconst", "M"]
LABELS = {
    "G": r"$G$",
    "EG": r"$EG$",
    "M0": r"$M_0$",
    "Mconst": r"$M_{\mathrm{const}}$",
    "M": r"$M$",
}
COLORS = {"G": "#666666", "EG": "#0072B2", "M0": "#CC79A7",
          "Mconst": "#E69F00", "M": "#009E73"}
SOURCES: dict[str, dict] = {}
PRODUCTS: dict[str, list[str]] = {}


def read_csv(path: Path) -> list[dict]:
    relative = str(path.relative_to(ROOT))
    SOURCES[relative] = {
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "rows": 0,
    }
    with path.open(newline="") as stream:
        rows = list(csv.DictReader(stream))
    SOURCES[relative]["rows"] = len(rows)
    return rows


def interval(row: dict, key: str) -> np.ndarray:
    values = np.asarray(json.loads(row[key]), dtype=float)
    assert values.shape == (2,) and values[0] <= values[1]
    return values


def mean_field(value: str) -> float:
    parsed = json.loads(value)
    return float(parsed["mean"] if isinstance(parsed, dict) else parsed)


def fixed(value: float, digits: int) -> str:
    """Format with fixed decimals, printing values that round to zero as unsigned zero."""
    text = f"{value:.{digits}f}"
    return text[1:] if text.startswith("-") and float(text) == 0 else text


def tex_interval(value: float, limits, scale=1.0, digits=1) -> str:
    low, high = np.asarray(limits) * scale
    return (f"${fixed(value * scale, digits)}\\ [{fixed(low, digits)},\\ "
            f"{fixed(high, digits)}]$")


def table(name: str, columns: str, header: str, rows: list[str],
          inputs: list[Path]) -> None:
    target = PAPER / "tables" / name
    target.write_text(
        "% Generated by paper/build_assets.py from saved report summaries.\n"
        f"\\begin{{tabular}}{{{columns}}}\n\\toprule\n"
        + header + " \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n"
    )
    PRODUCTS[str(target.relative_to(ROOT))] = [
        str(path.relative_to(ROOT)) for path in inputs
    ]


def save_figure(fig, name: str, inputs: list[Path]) -> None:
    target = PAPER / "figures" / (name + ".pdf")
    fig.savefig(target, metadata={"CreationDate": None, "ModDate": None},
                bbox_inches="tight")
    fig.savefig(PAPER / "figures" / (name + ".png"), dpi=180,
                bbox_inches="tight")
    PRODUCTS[str(target.relative_to(ROOT))] = [
        str(path.relative_to(ROOT)) for path in inputs
    ]
    plt.close(fig)


def panel_letter(ax, letter: str) -> None:
    """Bold panel letter at the upper left; the caption describes each panel."""
    ax.set_title(letter, loc="left", fontweight="bold")


def yule_figure() -> None:
    source = BD / "one-type-quantiles.csv"
    rows = read_csv(source)
    fig, axes = plt.subplots(2, 2, figsize=(7.0, 6.2), layout="constrained")
    variables = (r"$N(t)$", r"$Y$")
    for i, noisy in enumerate((False, True)):
        for j, time in enumerate((0.5, 5.0)):
            ax = axes[i, j]
            selected = [
                row for row in rows
                if float(row["d"]) == 0 and int(row["n"]) == 1
                and float(row["time"]) == time
                and (row["noisy"] == "True") == noisy
            ]
            all_values = []
            for method, marker in (("G", "s"), ("M0", "^"), ("M", "o")):
                points = sorted(
                    [row for row in selected if row["method"] == method],
                    key=lambda row: float(row["probability"]),
                )
                assert len(points) == 13
                x = [float(row["exact"]) for row in points]
                y = [float(row["approximate"]) for row in points]
                all_values.extend(x + y)
                ax.plot(x, y, marker=marker, markersize=3.4, linewidth=1.2,
                        color=COLORS[method], label=LABELS[method])
            low, high = min(all_values), max(all_values)
            pad = 0.06 * (high - low)
            limits = (low - pad, high + pad)
            ax.plot(limits, limits, color="black", linewidth=0.8,
                    linestyle="--", zorder=0)
            ax.set(xlim=limits, ylim=limits,
                   xlabel=f"Exact quantile of {variables[i]} (cells)",
                   ylabel=f"Approximate quantile of {variables[i]} (cells)")
            panel_letter(ax, "ABCD"[i * 2 + j])
            ax.set_aspect("equal", adjustable="box")
    handles, labels = axes[0, 0].get_legend_handles_labels()
    labels[0] = r"$G=EG$"
    fig.legend(handles, labels, loc="outside lower center", ncols=3, frameon=False)
    save_figure(fig, "figure-1-yule", [source])


def prediction_figure() -> None:
    source = BD / "delivery2-scores.csv"
    rows = read_csv(source)
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.5), layout="constrained")
    combinations = [(1, 9), (1, 11), (2, 9), (2, 11)]
    for ax, founders, letter in zip(axes, (1, 50), "AB"):
        for comparison, offset, color, marker in (
            ("M-G", -0.12, COLORS["G"], "o"),
            ("M-EG", 0.12, COLORS["EG"], "s"),
        ):
            selected = []
            for founder_type, time in combinations:
                matched = [
                    row for row in rows
                    if int(row["founders"]) == founders
                    and int(row["founder_type"]) == founder_type
                    and float(row["time"]) == time
                    and row["comparison"] == comparison
                ]
                assert len(matched) == 1 and int(matched[0]["n"]) == 500
                selected.append(matched[0])
            ax.errorbar(
                [float(row["mean"]) for row in selected],
                np.arange(4) + offset,
                xerr=[1.96 * float(row["se"]) for row in selected],
                fmt=marker, color=color, markersize=4, capsize=2,
                label=" minus ".join(LABELS[m] for m in comparison.split("-")),
            )
        ax.axvline(0, color="black", linestyle="--", linewidth=0.8)
        ax.set(yticks=np.arange(4),
               yticklabels=[f"Type {kind}, day {time}" for kind, time in combinations],
               xlabel="Mean paired log-density difference",
               ylim=(3.5, -0.5))
        panel_letter(ax, letter)
        ax.grid(axis="x", alpha=0.2)
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="outside lower center", ncols=2, frameon=False)
    save_figure(fig, "figure-2-prediction", [source])


def inference_figure() -> list[dict]:
    source = BD / "mconst-metrics.csv"
    paired_sources = [BD / "delivery3-paired.csv", BD / "mconst-paired.csv"]
    original, added = [read_csv(path) for path in paired_sources]
    rows = read_csv(source)
    assert len(rows) == 20
    assert all(int(row["successful"]) == 100
               and int(row["profile_resolved"]) == 100
               and int(row["failures"]) == 0 for row in rows)
    fig, axes = plt.subplots(3, 2, figsize=(7.2, 7.8), sharey="row",
                             layout="constrained")
    metric_names = ("rmse_reduction", "coverage", "mean_length")
    ylabels = ("RMSE reduction (%)", "Coverage (%)", "Mean total set length (per day)")
    for col, founders in enumerate((1, 50)):
        for i, (metric, ylabel) in enumerate(zip(metric_names, ylabels)):
            ax = axes[i, col]
            methods = METHODS[:-1] if metric == "rmse_reduction" else METHODS
            for index, method in enumerate(methods):
                for rate, offset, marker in (("b1", -0.14, "o"), ("b2", 0.14, "s")):
                    if metric == "rmse_reduction":
                        pool = added if method == "Mconst" else original
                        selected = [row for row in pool
                                    if int(row["founders"]) == founders
                                    and row["comparison"] == "M-" + method
                                    and row["rate"] == rate]
                    else:
                        selected = [row for row in rows
                                    if int(row["founders"]) == founders
                                    and row["method"] == method and row["rate"] == rate]
                    assert len(selected) == 1
                    row = selected[0]
                    if metric == "rmse_reduction":
                        assert int(row["paired_successful"]) == 100
                        assert json.loads(row["excluded_replicates"]) == []
                    scale = 1 if metric == "mean_length" else 100
                    value = float(row[metric]) * scale
                    if metric == "mean_length":
                        error = np.array([float(row["length_mcse"])] * 2) * scale
                    else:
                        limits = interval(row, metric + "_ci95") * scale
                        error = np.array([value - limits[0], limits[1] - value])
                    assert np.all(error >= 0)
                    ax.errorbar(index + offset, value, yerr=error[:, None],
                                fmt=marker, color=COLORS[method], markersize=4.2,
                                capsize=2, linewidth=1.1)
            ax.set(xticks=np.arange(len(methods)),
                   xticklabels=[LABELS[m] for m in methods],
                   xlim=(-0.6, len(methods) - 0.4), ylabel=ylabel)
            ax.tick_params(labelleft=True)
            panel_letter(ax, "ABCDEF"[i * 2 + col])
            ax.grid(axis="y", alpha=0.2)
            if metric == "rmse_reduction":
                ax.axhline(0, linestyle="--", color="black", linewidth=0.8)
                ax.set(ylim=(-20, 25), xlabel=r"Comparator $H$")
            elif metric == "coverage":
                ax.axhline(90, linestyle="--", color="black", linewidth=0.8)
                ax.set_ylim(35, 100)
            else:
                ax.set_ylim(0, 0.085)
    handles = [Line2D([], [], marker=marker, linestyle="none", color="black",
                      label=label) for marker, label in (("o", r"$b_1$"), ("s", r"$b_2$"))]
    fig.legend(handles=handles, loc="outside lower center", ncols=2, frameon=False)
    save_figure(fig, "figure-3-inference", [source, *paired_sources])
    return rows


def prediction_table() -> None:
    source = BD / "delivery2-scores.csv"
    rows = read_csv(source)
    digits = {"M-G": 3, "M-EG": 3, "M-M0": 1}
    lines = []
    for founders in (1, 50):
        for founder_type in (1, 2):
            for time in (9, 11):
                cells = []
                for comparison, places in digits.items():
                    matched = [
                        row for row in rows
                        if int(row["founders"]) == founders
                        and int(row["founder_type"]) == founder_type
                        and float(row["time"]) == time
                        and row["comparison"] == comparison
                    ]
                    assert len(matched) == 1 and int(matched[0]["n"]) == 500
                    mean, se = float(matched[0]["mean"]), float(matched[0]["se"])
                    cells.append(f"${mean:.{places}f}\\ ({se:.{places}f})$")
                lines.append(f"{founders} & {founder_type} & {time} & "
                             + " & ".join(cells) + " \\\\")
        lines.append("\\addlinespace")
    table("prediction.tex", "@{}rrrrrr@{}",
          "$N_0$ & Founder type & Day & $M$ minus $G$ & $M$ minus $EG$ & $M$ minus $M_0$",
          lines, [source])


def no_death_table() -> None:
    paths = []
    lines = []
    for window, directory in (("5, 7", "founder-mixture-pilot"),
                              ("9, 11", "founder-mixture-pilot-days-9-11")):
        folder = ROOT / "reports" / directory / "tables"
        paths.extend([folder / "inference.csv", folder / "paired-inference.csv"])
        metrics = read_csv(paths[-2])
        pairs = read_csv(paths[-1])
        for rate in ("b1", "b2"):
            def one_metric(method):
                return next(row for row in metrics if int(row["founders"]) == 1
                            and row["method"] == method and row["rate"] == rate)
            def one_pair(comparator):
                return next(row for row in pairs if int(row["founders"]) == 1
                            and row["comparison"] == "M-" + comparator
                            and row["rate"] == rate)
            paired = [one_pair(method) for method in ("G", "M0")]
            rates = [one_metric(method) for method in ("G", "M", "M0")]
            assert all(int(row["successful"]) == 100 for row in rates)
            coverage = "/".join(f'{100 * float(row["coverage"]):.0f}' for row in rates)
            length_ratio = float(rates[1]["average_set_length"]) / float(rates[0]["average_set_length"])
            lines.append(
                f"{window} & $b_{rate[-1]}$ & "
                + " & ".join(tex_interval(float(row["rmse_reduction"]),
                                         interval(row, "rmse_reduction_ci95"), 100)
                             for row in paired)
                + f" & {coverage} & {length_ratio:.2f} \\\\"
            )
    table("no-death.tex", "@{}llrrrr@{}",
          "Days & Rate & vs. $G$ & vs. $M_0$ & Coverage & Length ratio",
          lines, paths)


def paired_table() -> None:
    paths = [BD / "delivery3-paired.csv", BD / "mconst-paired.csv"]
    original, added = [read_csv(path) for path in paths]
    lines = []
    for founders in (1, 50):
        for rate in ("b1", "b2"):
            for comparator in ("G", "EG", "M0", "Mconst"):
                pool = added if comparator == "Mconst" else original
                row = next(row for row in pool if int(row["founders"]) == founders
                           and row["rate"] == rate
                           and row["comparison"] == "M-" + comparator)
                assert int(row["paired_successful"]) == 100
                assert int(row["paired_profiles"]) == 100
                assert json.loads(row["excluded_replicates"]) == []
                lines.append(
                    f"{founders} & $b_{rate[-1]}$ & {LABELS[comparator]} & "
                    + tex_interval(float(row["rmse_reduction"]),
                                   interval(row, "rmse_reduction_ci95"), 100)
                    + " & " + tex_interval(mean_field(row["coverage_difference"]),
                                          interval(row, "coverage_difference_ci95"), 100)
                    + " & " + tex_interval(mean_field(row["length_difference"]),
                                          interval(row, "length_difference_ci95"), 1000, 2)
                    + " \\\\"
                )
            lines.append("\\addlinespace")
    table("paired.tex", "@{}rllrrr@{}",
          "$N_0$ & Rate & Comparator & RMSE reduction (\\%) & Coverage gain (pp) & Length change",
          lines, paths)


def bias_table(rows: list[dict]) -> None:
    lines = []
    for founders in (1, 50):
        for rate in ("b1", "b2"):
            for method in METHODS:
                row = next(row for row in rows if int(row["founders"]) == founders
                           and row["method"] == method and row["rate"] == rate)
                bias = f'${float(row["bias"]):.5f}\\ ({float(row["bias_mcse"]):.5f})$'
                rmse = tex_interval(float(row["rmse"]), interval(row, "rmse_ci95"),
                                    digits=5)
                lines.append(f"{founders} & $b_{rate[-1]}$ & {LABELS[method]} & "
                             + bias + " & " + rmse + " \\\\")
            lines.append("\\addlinespace")
    table("bias.tex", "@{}rllrr@{}",
          "$N_0$ & Rate & Method & Bias (MCSE) & RMSE [95\\% interval]",
          lines, [BD / "mconst-metrics.csv"])


def main() -> None:
    for folder in ("figures", "tables"):
        (PAPER / folder).mkdir(exist_ok=True)
    plt.rcParams.update({
        "font.size": 9, "axes.titlesize": 10, "axes.labelsize": 9,
        "axes.spines.top": False, "axes.spines.right": False,
        "pdf.fonttype": 42, "ps.fonttype": 42,
    })
    yule_figure()
    prediction_figure()
    prediction_table()
    rows = inference_figure()
    no_death_table()
    paired_table()
    bias_table(rows)
    manifest = {
        "purpose": "Presentation of saved results only; no simulation, fitting, or bootstrap rerun.",
        "script": "paper/build_assets.py",
        "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "sources": SOURCES,
        "products": PRODUCTS,
        "checks": {
            "birth_death_method_rate_founder_combinations": len(rows),
            "all_birth_death_fits_and_profiles_resolved": True,
            "paired_tables_use_100_common_datasets_without_exclusions": True,
            "quantile_points_per_curve": 13,
        },
    }
    (PAPER / "asset-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Created 3 figures and {sum(p.startswith('paper/tables/') for p in PRODUCTS)} tables "
          f"from {len(SOURCES)} saved tables.")


if __name__ == "__main__":
    main()
